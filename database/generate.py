"""Regenerate both reviewed initial schema artifacts from the ORM metadata."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'backend'))
from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.schema import CreateTable, CreateIndex
from app.models import Base

root = Path(__file__).resolve().parent
for name, dialect in [('postgresql', postgresql.dialect()), ('sqlite', sqlite.dialect())]:
    excluded = {'sync_receipts', 'site_sync_heads', 'site_changes', 'technicians', 'device_access', 'site_grants'} if name == 'sqlite' else {'sync_outbox', 'sync_cursors'}
    statements = ['-- Generated by database/generate.py; initial migration only.']
    if name == 'sqlite':
        statements += ['PRAGMA foreign_keys = ON;', 'PRAGMA journal_mode = WAL;']
    for table in Base.metadata.sorted_tables:
        if name == 'postgresql' and table.name in {'technicians','device_access','site_grants'}:
            continue # Added by migrations/002_device_access.sql, keep v1 immutable.
        if table.name in excluded:
            continue
        statements.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ';')
        for index in sorted(table.indexes, key=lambda i: i.name):
            statements.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ';')
    (root / f'{name}.sql').write_text('\n\n'.join(statements) + '\n')
